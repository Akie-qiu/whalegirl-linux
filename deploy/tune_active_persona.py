def tune_prompt(prompt):
    value = prompt
    for before, after in REPLACEMENTS:
        if value.count(before) != 1:
            raise ValueError('当前有效角色卡已变化，不能盲目覆盖；缺少唯一修改位置')
        value = value.replace(before, after, 1)
    if len(value) > 16000:
        raise ValueError('角色卡超过长度限制')
    return value
